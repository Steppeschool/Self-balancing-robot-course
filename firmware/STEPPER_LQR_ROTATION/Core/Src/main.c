/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  float ref1, ref2;
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flashdnterface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_TIM4_Init();
  MX_TIM8_Init();
  MX_TIM15_Init();
  MX_SPI2_Init();
  MX_SPI1_Init();
  /* USER CODE BEGIN 2 */
  //reset_encoder(&encoder_inverted, &htim2);
  HAL_Delay(1000);
  l6470_init(&motor_sets);
  l6470_enable(&motor_sets);
  icm_20948_init();
  icm_20948_read_data(&icm_data);
  sensor2imu(icm_data, &imu_norm_data);
  complementary_filter_euler(imu_norm_data,  &euler_angles_robot);
  euler_angles_old = euler_angles_robot;
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	  if(timer_flag)
	  {
		timer_flag = 0;
		ref1 = get_reference(RC_CHANNEL1);
		ref2 = get_reference(RC_CHANNEL2);
		ref1_position += ref1 / SAMPLE_RATE;
		icm_20948_read_data(&icm_data);
		sensor2imu(icm_data, &imu_norm_data);
		complementary_filter_euler(imu_norm_data,  &euler_angles_robot);
		if(start_balancing)
		{
			robot_state.angle = euler_angles_robot.pitch;
			robot_state.angle_vel = robot_state.angle_vel * 0.1 + 0.9 * (euler_angles_robot.pitch -
						  euler_angles_old.pitch) * SAMPLE_RATE;
			robot_state.position = (motor_sets.motors[0].speed_pos.rad_pos +
					motor_sets.motors[1].speed_pos.rad_pos) / 2 - ref1_position;
			robot_state.velocity = (motor_sets.motors[0].speed_pos.rad_speed +
					motor_sets.motors[1].speed_pos.rad_speed) / 2 - ref1;
			apply_lqr(robot_state, &force);
			vel_temp[0] += (force) / (2.0 * MASS_ROBOT * DIAMETER * SAMPLE_RATE);
			vel_temp[1] += (force) / (2.0 * MASS_ROBOT * DIAMETER * SAMPLE_RATE);
		}
		else
		{
			 vel_temp[0] = 0;
			 vel_temp[1] = 0;
			 ref2 = 0;
			 ref1 = 0;
			 force = 0;
			 ref1_position = 0;
			 l6470_reset_speed_pos(&motor_sets);
			 reset_state_lqr(&robot_state);
		}
		if (euler_angles_robot.pitch < 1.3 && euler_angles_robot.pitch > -1.3 &&
				euler_angles_robot.roll < 0.9 && euler_angles_robot.roll > -0.9)
		{
			// motor is in upright position
			if(euler_angles_robot.pitch < 0.3 && euler_angles_robot.pitch > -0.3 &&
				euler_angles_robot.roll < 0.2 && euler_angles_robot.roll > -0.2)
			{
				// wait one sec, then start balancing
				if(!start_balancing)
				{
					count_start_banaling++;
				}
				if(count_start_banaling > SAMPLE_RATE)
				{
					start_balancing = 1;
					count_start_banaling = 0;
				}
			}
		}
		else
		{
		 start_balancing = 0;
		}
		if(motor_sets.motors[1].speed_pos.rad_speed == MAX_SPEED_RAD &&
				motor_sets.motors[0].speed_pos.rad_speed == MAX_SPEED_RAD)
		{
			count_off_ground++;
		}

		vel_final[0] = vel_temp[0] + ref2 / 2;
		vel_final[1] = vel_temp[0] - ref2 / 2;

		l6470_set_vel(&motor_sets, vel_final);
		euler_angles_old = euler_angles_robot;
	  }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

